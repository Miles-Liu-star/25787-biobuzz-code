package org.firstinspires.ftc.teamcode.pedroPathing;

import com.pedropathing.algorithm.Foresight;
import com.pedropathing.algorithm.ForesightConfig;
import com.pedropathing.controllers.Controller;
import com.pedropathing.follower.Follower;
import com.pedropathing.math.Matrix;
import com.pedropathing.math.Vector2D;
import com.pedropathing.revhub.drivetrains.Mecanum;
import com.pedropathing.revhub.drivetrains.MecanumConfig;
import com.pedropathing.revhub.localizers.PinpointConfig;
import com.pedropathing.revhub.localizers.PinpointLocalizer;
import com.qualcomm.hardware.gobilda.GoBildaPinpointDriver;
import com.qualcomm.robotcore.hardware.DcMotorSimple;
import com.qualcomm.robotcore.hardware.HardwareMap;

import org.firstinspires.ftc.robotcore.external.navigation.DistanceUnit;
import org.firstinspires.ftc.teamcode.pinpoint.PinPointConfig;

/** Pedro Pathing hardware wiring and conservative, not-yet-tuned Foresight values. */
public final class Constants {
    /** Matches the motor names and directions used by DriveSubsystem. */
    public static final MecanumConfig drivetrainConfig = new MecanumConfig(c -> {
        c.frontLeftName.set("0");
        c.backLeftName.set("1");
        c.frontRightName.set("2");
        c.backRightName.set("3");

        c.frontLeftDirection.set(DcMotorSimple.Direction.REVERSE);
        c.backLeftDirection.set(DcMotorSimple.Direction.FORWARD);
        c.frontRightDirection.set(DcMotorSimple.Direction.FORWARD);
        c.backRightDirection.set(DcMotorSimple.Direction.REVERSE);
        c.manualBrakeMode.set(true);
    });

    /** Converts the project's Pinpoint offsets from millimeters to Pedro's default inches. */
    public static PinpointConfig localizerConfig = new PinpointConfig(c -> {
        c.name.set("pinpoint");
        c.podType.set(GoBildaPinpointDriver.GoBildaOdometryPods.goBILDA_4_BAR_POD);
        c.xPodOffset.set(-3.307086614173228);
        c.yPodOffset.set(-6.333661417322835);
        c.xPodDirection.set(GoBildaPinpointDriver.EncoderDirection.REVERSED);
        c.yPodDirection.set(GoBildaPinpointDriver.EncoderDirection.REVERSED);
        c.globalDistanceUnit.set(DistanceUnit.INCH);
        c.offsetUnits.set(DistanceUnit.INCH);
    });

    public static ForesightConfig foresightConfig = new ForesightConfig(
            c -> {
                Controller primaryTranslationalForward = Controller.proportional(0.3273297009039939);
                Controller secondaryTranslationalForward = Controller.proportional(0.12093957807333265);
                Controller primaryTranslationalLateral = Controller.proportional(0.47014103566345544);
                Controller secondaryTranslationalLateral = Controller.proportional(0.1737045502778088);

                c.forwardTranslational.set(Controller.piecewise(secondaryTranslationalForward).put(2.5, primaryTranslationalForward));
                c.strafeTranslational.set(Controller.piecewise(secondaryTranslationalLateral).put(2.5, primaryTranslationalLateral));

                c.coast.set(Controller.proportionalFeedforward(0.01335087059504063));
                c.brake.set(Controller.proportionalFeedforward(0.011348240005784535));

                c.headingFeedback.set(Controller.proportional(4.883900070453382));
                c.headingBrakeCoefficients.set(Vector2D.cartesian(0.05681526016350793, 0.005475024422216216));

                c.linearBrakeCoefficients.set(Matrix.diag(0.12209329215563336, 0.05891606940308479));
                c.quadraticBrakeCoefficients.set(Matrix.diag(7.850788698163614E-4, 0.0018659546951461036));

                c.maxAchievableForwardVelocity.set(76.35018619681838);
                c.maxAchievableStrafeVelocity.set(65.0957899199647);
                c.naturalForwardDeceleration.set(36.06259830279264);
                c.naturalStrafeDeceleration.set(141.62627008191924);
            }
    );
    /**
     * Low-speed bootstrap values so Follower can be constructed. Replace them with the
     * Java block generated by the Foresight AutoTune before relying on autonomous paths.
     */

    private Constants() {}
    public static Follower create(HardwareMap h) {
        return new Follower(
        new PinpointLocalizer(h, localizerConfig),
        new Mecanum(h, drivetrainConfig),
        new Foresight(foresightConfig)
        );
    }
}
